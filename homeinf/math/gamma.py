# Частота (высота) ноты ля (А) 1 октавы равна 440 Гц.
# Каждая следующая нота больше, а предыдущая - меньше ровно на корень 12 степени из 2.
# Напечатать таблицу отношений между всеми нотами 1 октавы (а также до 2 октавы).
# 'c' это 'C4', 'C' это 'C5', 'C2' это 'C6'

# -----------------------------------------------------

# f_a1 = 440
# f_a2 = f_a1 * 2
# f_a3 = f_a2 * 2

# f_a1s = f_a1 + (f_a2 - f_a1)/12
# f_a2s = f_a2 + (f_a3 - f_a2)/12

# print("отношение для ля", f_a2 / f_a1)
# print("отношение для ля-диез", f_a2s / f_a1s)

print("\n------------------------------\n")

# -----------------------------------------------------

mul = 2**(1/12)
print("множитель:", mul)

notes = "c c# d d# e f f# g g# a b h C C# D D# E F F# G G# A B H C2".split()

freqs = {}
freqs['a'] = 440.

nf = 440.
for note in "c c# d d# e f f# g g#".split()[::-1]:
    freqs[note] = nf / mul
    nf /= mul
nf = 440.
for note in "b h C C# D D# E F F# G G# A B H C2".split():
    freqs[note] = nf * mul
    nf *= mul

print("частоты:", freqs, "\n")

print("%8s" % "", end="")
for second in notes:
    print("%-6s" % second, end="")
print()
for first in notes:
    print("%6s" % first, end="")
    for second in notes:
        print("%6.2f" % (freqs[second] / freqs[first]), end="")
    print()        

print()


